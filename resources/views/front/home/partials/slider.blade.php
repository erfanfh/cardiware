<script>
    // Hero Swiper (بدون تغییر ظاهر: ناوبری با دکمه‌های خودت + دات‌های خودت)
    const heroEl = document.querySelector('.heroSwiper');
    const heroDots = heroEl?.closest('.rounded-2xl')?.querySelectorAll('.heroDots');

    const hero = new Swiper('.heroSwiper', {
        loop: true,
        speed: 550,
        autoplay: {
            delay: 6500,
            disableOnInteraction: false,
            pauseOnMouseEnter: true,
        },
        navigation: {
            nextEl: '.heroNext',
            prevEl: '.heroPrev',
        },
        on: {
            init(sw) {
                syncDots(sw);
            },
            slideChange(sw) {
                syncDots(sw);
            }
        }
    });

    function syncDots(sw) {
        // چون loop فعاله، realIndex درست‌ترینه (0..n-1)
        const i = sw.realIndex;
        document.querySelectorAll('.heroDots').forEach((wrap) => {
            const spans = wrap.querySelectorAll('span');
            if (!spans.length) return;

            spans.forEach((s, idx) => {
                // idx 0 = active pill، idx 1.. = dots
                if (idx === 0) {
                    // pill: active on current
                    s.classList.toggle('bg-brand-400', true);
                    s.classList.toggle('bg-white/40', false);
                    s.classList.toggle('w-8', true);
                    s.classList.toggle('w-2', false);
                    s.classList.toggle('rounded-full', true);
                } else {
                    const dotIndex = idx - 1; // 0..2
                    const active = dotIndex === i;
                    s.classList.toggle('bg-white/40', !active);
                    s.classList.toggle('bg-brand-400', active);
                }
            });

            // برای هماهنگی تعداد دات‌ها با تعداد اسلایدها (اینجا 3 اسلاید)
            // اگر تعداد اسلایدها رو زیاد کردی، همین spans رو هم بیشتر کن.
        });
    }
</script>
